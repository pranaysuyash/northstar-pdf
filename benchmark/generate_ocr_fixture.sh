#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MAGICK="${MAGICK_BIN:-$(command -v magick || command -v convert || true)}"
if [[ -z "$MAGICK" ]]; then
  printf 'BLOCKED: ImageMagick is not installed.\n' >&2
  exit 2
fi

OUTPUT_DIR="${PDF_EDITOR_OCR_OUTPUT_DIR:-$ROOT/benchmark/results/ocr-corpus}"
FONT="${PDF_EDITOR_OCR_FONT:-/System/Library/Fonts/Supplemental/Verdana.ttf}"
mkdir -p "$OUTPUT_DIR"
PNG="$OUTPUT_DIR/printed-scan.png"
PDF="$OUTPUT_DIR/printed-scan.pdf"

# ImageMagick PDF output embeds renderer metadata and is not byte-stable
# across regeneration. Retain the reviewed golden PDF so provenance remains
# meaningful; regenerate it manually only when the fixture policy changes.
if [[ ! -f "$PDF" ]]; then
  "$MAGICK" -size 1600x700 xc:white \
    -font "$FONT" -gravity center -fill black -pointsize 54 \
    -annotate +0-70 'OCR SAMPLE 2026' \
    -pointsize 42 -annotate +0+10 'Applicant: Ada Lovelace' \
    -pointsize 38 -annotate +0+80 'Reference: OCR-042' \
    "$PNG"
  "$MAGICK" "$PNG" "$PDF"
fi

cat > "$OUTPUT_DIR/ground-truth.txt" <<'EOF'
OCR SAMPLE 2026
Applicant: Ada Lovelace
Reference: OCR-042
EOF

cat > "$OUTPUT_DIR/README.txt" <<EOF
Generated by: benchmark/generate_ocr_fixture.sh
Artifact: printed-scan.pdf
The PDF intentionally contains a raster image and no authored text layer.
Ground truth is recorded in ground-truth.txt for OCR benchmarking only.
EOF

printf 'Generated OCR fixture in %s\n' "${OUTPUT_DIR#$ROOT/}"
