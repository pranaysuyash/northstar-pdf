#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MAGICK="${MAGICK_BIN:-$(command -v magick || command -v convert || true)}"
OUTPUT_DIR="${PDF_EDITOR_GOVERNED_CORPUS_OUTPUT_DIR:-$ROOT/benchmark/results/governed-corpus}"
HANDWRITTEN_PNG="$OUTPUT_DIR/handwritten-simulated-entries.png"
HANDWRITTEN_PDF="$OUTPUT_DIR/handwritten-simulated-entries.pdf"
GROUND_TRUTH="$OUTPUT_DIR/handwritten-simulated-ground-truth.txt"
README="$OUTPUT_DIR/README.txt"

if [[ -z "$MAGICK" ]]; then
  printf 'BLOCKED: ImageMagick is not installed.\n' >&2
  exit 2
fi

HAND_FONT="${PDF_EDITOR_HANDWRITING_FONT:-/System/Library/Fonts/Supplemental/Bradley Hand Bold.ttf}"
LABEL_FONT="${PDF_EDITOR_LABEL_FONT:-/System/Library/Fonts/Supplemental/Verdana.ttf}"
[[ -f "$HAND_FONT" ]] || { printf 'ERROR: handwriting font not found: %s\n' "$HAND_FONT" >&2; exit 2; }
[[ -f "$LABEL_FONT" ]] || { printf 'ERROR: label font not found: %s\n' "$LABEL_FONT" >&2; exit 2; }

mkdir -p "$OUTPUT_DIR"

# This is a synthetic handwriting-like raster fixture. It contains no personal
# source material and must not be used as evidence for genuine handwriting
# recognition. The visual noise and ruled regions exercise page segmentation,
# OCR abstention, field association, and preservation paths.
"$MAGICK" -size 1800x1100 xc:'#fffdf6' \
  -font "$LABEL_FONT" -fill '#202a35' -pointsize 46 \
  -annotate +120+120 'HANDWRITTEN COMPLETION SAMPLE' \
  -pointsize 30 -annotate +120+185 'Synthetic raster fixture. No real person or document.' \
  -stroke '#6b7280' -strokewidth 3 -fill none \
  -draw 'line 120,260 1680,260 line 120,430 1680,430 line 120,600 1680,600 line 120,770 1680,770 line 120,940 1680,940' \
  -font "$LABEL_FONT" -fill '#374151' -stroke none -pointsize 34 \
  -annotate +145+325 'Applicant name:' \
  -annotate +145+495 'Reference:' \
  -annotate +145+665 'Date:' \
  -annotate +145+835 'Signature appearance:' \
  -annotate +145+1005 'Review note:' \
  -font "$HAND_FONT" -fill '#123c70' -pointsize 58 \
  -annotate +620+330 'Ada Lovelace' \
  -annotate +620+500 'HW-2048' \
  -annotate +620+670 '25 Aug 2026' \
  -annotate +620+840 'Ada L.' \
  -font "$HAND_FONT" -pointsize 44 \
  -annotate +620+1015 'check spacing' \
  -stroke '#123c70' -strokewidth 5 -fill none \
  -draw 'line 1450,320 1510,280 line 1510,280 1560,320 line 1460,500 1520,450 line 1520,450 1580,500 line 1450,670 1520,630 line 1520,630 1590,670' \
  "$HANDWRITTEN_PNG"

"$MAGICK" "$HANDWRITTEN_PNG" "$HANDWRITTEN_PDF"

printf '%s\n' \
  'HANDWRITTEN COMPLETION SAMPLE' \
  'Applicant name: Ada Lovelace' \
  'Reference: HW-2048' \
  'Date: 25 Aug 2026' \
  'Signature appearance: Ada L.' \
  'Review note: check spacing' \
  > "$GROUND_TRUTH"

printf '%s\n' \
  'Generated by: benchmark/generate_governed_corpus.sh' \
  'Artifact: handwritten-simulated-entries.pdf' \
  'Image source: handwritten-simulated-entries.png' \
  'Privacy class: synthetic-local' \
  'Handwriting class: simulated handwriting-like glyphs rendered with a local system font; not genuine handwriting evidence.' \
  'Ground truth: handwritten-simulated-ground-truth.txt is synthetic OCR calibration text.' \
  'Retention: retain locally for benchmark and regression use; do not upload or use for human biometric inference.' \
  > "$README"

printf 'Generated governed handwritten fixture in %s\n' "${OUTPUT_DIR#$ROOT/}"
