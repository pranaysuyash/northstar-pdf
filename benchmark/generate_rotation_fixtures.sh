#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
QPDF="${QPDF_BIN:-$(command -v qpdf || true)}"
if [[ -z "$QPDF" ]]; then
  printf 'BLOCKED: qpdf is not installed.\n' >&2
  exit 2
fi

WIDGET_SOURCE="${PDF_EDITOR_ROTATION_WIDGET_SOURCE:-$ROOT/benchmark/results/2026-08-23-pdfkit-widgets/fixture.pdf}"
FORM_SOURCE="${PDF_EDITOR_ROTATION_FORM_SOURCE:-$ROOT/docs/benchmarks/pdfkit-form6-run-2026-08-23/noop.pdf}"
OUTPUT_DIR="${PDF_EDITOR_ROTATION_OUTPUT_DIR:-$ROOT/benchmark/results/rotation-corpus}"

[[ -f "$WIDGET_SOURCE" ]] || { printf 'ERROR: widget source fixture not found: %s\n' "$WIDGET_SOURCE" >&2; exit 2; }
[[ -f "$FORM_SOURCE" ]] || { printf 'ERROR: form source fixture not found: %s\n' "$FORM_SOURCE" >&2; exit 2; }
mkdir -p "$OUTPUT_DIR"

"$QPDF" --deterministic-id --rotate=+90:1 -- "$WIDGET_SOURCE" "$OUTPUT_DIR/rotated-widget-90.pdf"
set +e
"$QPDF" --deterministic-id --rotate=+90:1 --rotate=+180:2 -- "$FORM_SOURCE" "$OUTPUT_DIR/rotated-form6-mixed.pdf"
rotation_status=$?
set -e
[[ -f "$OUTPUT_DIR/rotated-form6-mixed.pdf" ]] || {
  printf 'ERROR: qpdf did not produce the mixed-rotation fixture (exit %s).\n' "$rotation_status" >&2
  exit 1
}

cat > "$OUTPUT_DIR/README.txt" <<EOF
Generated by: benchmark/generate_rotation_fixtures.sh
Widget source: ${WIDGET_SOURCE#$ROOT/}
Form source: ${FORM_SOURCE#$ROOT/}
rotated-widget-90.pdf: one-page synthetic widget fixture with page rotation 90 degrees.
rotated-form6-mixed.pdf: two-page static form with page 1 rotated 90 degrees and page 2 rotated 180 degrees.
The source fixtures remain immutable; qpdf writes new derived files.
EOF

printf 'Generated rotation fixtures in %s\n' "${OUTPUT_DIR#$ROOT/}"
