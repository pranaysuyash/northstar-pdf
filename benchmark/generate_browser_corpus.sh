#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
QPDF="${QPDF_BIN:-$(command -v qpdf || true)}"
MAGICK="${MAGICK_BIN:-$(command -v magick || command -v convert || true)}"

if [[ -z "$QPDF" ]]; then
  printf 'BLOCKED: qpdf is not installed.\n' >&2
  exit 2
fi
if [[ -z "$MAGICK" ]]; then
  printf 'BLOCKED: ImageMagick is not installed.\n' >&2
  exit 2
fi

OUTPUT_DIR="${PDF_EDITOR_BROWSER_CORPUS_OUTPUT_DIR:-$ROOT/benchmark/results/browser-corpus}"
PUBLIC_SOURCE="$ROOT/benchmark/results/public-sample-form.pdf"
RASTER_SOURCE="$ROOT/benchmark/results/ocr-corpus/printed-scan.png"
HYBRID="$OUTPUT_DIR/hybrid-text-raster-form.pdf"
SCANNED_PNG="$OUTPUT_DIR/scanned-noisy.png"
SCANNED="$OUTPUT_DIR/scanned-noisy.pdf"
ROTATED="$OUTPUT_DIR/rotated-hybrid-90.pdf"
ENCRYPTED="$OUTPUT_DIR/encrypted-hybrid.pdf"
MALFORMED="$OUTPUT_DIR/malformed-hybrid-truncated.pdf"
LARGE="$OUTPUT_DIR/large-hybrid-40-pages.pdf"

[[ -f "$PUBLIC_SOURCE" ]] || { printf 'ERROR: public source fixture not found: %s\n' "$PUBLIC_SOURCE" >&2; exit 2; }
[[ -f "$RASTER_SOURCE" ]] || { printf 'ERROR: raster source fixture not found: %s\n' "$RASTER_SOURCE" >&2; exit 2; }
mkdir -p "$OUTPUT_DIR"

# The hybrid fixture has authored text and form structure from the public sample
# plus a separate raster-only page. It is a deterministic composition, not a
# claim about the public sample's external licensing.
"$QPDF" --deterministic-id --empty --pages "$PUBLIC_SOURCE" 1 "$ROOT/benchmark/results/ocr-corpus/printed-scan.pdf" 1 -- "$HYBRID"

# Make a deliberately degraded raster-only scan. Keep the original raster
# source untouched so the benchmark can compare clean and degraded OCR lanes.
"$MAGICK" "$RASTER_SOURCE" \
  -colorspace Gray \
  -attenuate 0.04 +noise Gaussian \
  -blur 0x0.35 \
  -contrast-stretch 2%x2% \
  "$SCANNED_PNG"
"$MAGICK" "$SCANNED_PNG" "$SCANNED"

"$QPDF" --deterministic-id --rotate=+90:1 --rotate=+90:2 -- "$HYBRID" "$ROTATED"
# qpdf does not permit deterministic IDs on encrypted output. Preserve the
# retained encrypted artifact on regeneration so its manifest digest remains a
# stable provenance anchor. Delete it only as an explicit fixture refresh.
if [[ ! -f "$ENCRYPTED" ]]; then
  "$QPDF" --encrypt reader-password owner-password 256 -- "$HYBRID" "$ENCRYPTED"
fi

# Retain a small, intentionally malformed input. The browser and native lanes
# must fail safely before emitting a document contract or export.
head -c 512 "$HYBRID" > "$MALFORMED"

page_args=()
for _ in $(seq 1 20); do
  page_args+=("$HYBRID" 1 "$HYBRID" 2)
done
"$QPDF" --deterministic-id --empty --pages "${page_args[@]}" -- "$LARGE"

cat > "$OUTPUT_DIR/README.txt" <<EOF
Generated by: benchmark/generate_browser_corpus.sh
Public/form source: benchmark/results/public-sample-form.pdf
Raster source: benchmark/results/ocr-corpus/printed-scan.png
hybrid-text-raster-form.pdf: authored text and form page plus raster-only page.
scanned-noisy.pdf: deterministic degraded raster-only derivative.
rotated-hybrid-90.pdf: hybrid source with both pages rotated 90 degrees.
encrypted-hybrid.pdf: AES-256 encrypted hybrid source; reader password is reader-password.
malformed-hybrid-truncated.pdf: first 512 bytes of the hybrid source; expected inspection failure.
large-hybrid-40-pages.pdf: 40-page repeated hybrid source for resource and navigation checks.
The files are derived local benchmark artifacts. External acquisition and license facts remain open.
EOF

printf 'Generated browser corpus in %s\n' "${OUTPUT_DIR#$ROOT/}"
